import type { ParsedInbound } from "./parse";

/**
 * Gelen iletinin türü (Aşama 13). Sınıflandırma YALNIZCA bir ön yargıdır: otomatik etki için ayrıca kanıt
 * katmanları (evidence.ts) geçmelidir. Belirsiz her durum `negative` veya `other` olarak insan incelemesine gider.
 */

export type InboundKind =
  /** Adres yok sınıfında kalıcı hata (5.1.1, 5.1.2, 5.1.10): tek suppression üreten bounce türü. */
  | "bounce_hard"
  /** Geçici hata (4.x.x veya Action: delayed). */
  | "bounce_soft"
  /** Bizim itibarımızla/politikayla ilgili ret (5.7.x): alıcının hatası değildir, suppression üretmez. */
  | "bounce_policy"
  /** Diğer kalıcı hatalar (kutu dolu 5.2.x vb.) ve yapısı belirsiz bounce benzeri iletiler. */
  | "bounce_other"
  | "auto_reply"
  | "unsubscribe"
  /** Olumsuz/ret ifadesi: asla otomatik suppression üretmez (K4). */
  | "negative"
  | "reply"
  /** RFC 5965 geri bildirim raporu, `Feedback-Type: abuse` (şikâyet). Otomatik etki için ayrıca kanıt gerekir. */
  | "complaint"
  /** Başka türde geri bildirim raporu (fraud, virus, other, not-spam, opt-out...): hiçbir otomatik etki yok. */
  | "feedback_other"
  | "other";

/** Alıcı adresinin var olmadığını bildiren kalıcı durum kodları. */
export const ADDRESS_GONE_STATUSES: ReadonlySet<string> = new Set(["5.1.1", "5.1.2", "5.1.10"]);

const SYSTEM_SENDER_RE = /^(mailer-daemon|postmaster)$/i;

export function isSystemSender(p: ParsedInbound): boolean {
  if (!p.from) return false;
  return SYSTEM_SENDER_RE.test(p.from.local);
}

/** Alıntı ve imza kısmını atar; yalnızca yeni yazılan metin kalır. */
export function freshText(text: string): string {
  const lines: string[] = [];
  for (const line of text.split(/\r?\n/)) {
    if (/^\s*>/.test(line)) continue;
    if (
      /^\s*(on .{5,80} wrote:|-----\s*original message|[a-z]+ .{3,60} (tarihinde|yazdı).*:)\s*$/i.test(
        line,
      )
    )
      break;
    lines.push(line);
    if (lines.length > 40) break;
  }
  return lines.join("\n").trim().slice(0, 2000);
}

const UNSUB_PHRASES =
  /\b(unsubscribe me|please unsubscribe|unsubscribe from|remove me from|take me off|opt[- ]?out|do not send (me )?(any )?(more )?(emails?|mail)|abonelikten çık|listeden çıkar|e-?posta (almak )?istemiyorum|mail atmayın|e-?posta göndermeyin)\b/i;
const UNSUB_SINGLE =
  /^\W*(unsubscribe|remove|remove me|stop|opt[- ]?out|çıkar|abonelikten çık)\W*$/i;
const NEGATIVE_PHRASES =
  /\b(not interested|no,? thank(s| you)|don'?t (contact|email|write)|do not (contact|email|write)|stop (emailing|contacting|writing)|leave us alone|ilgilenmiyoruz|ilgilenmiyorum|rahatsız etmeyin|istemiyoruz|kein interesse|pas intéress)/i;
const AUTO_SUBJECT =
  /^(automatic reply|auto(matic)? ?reply|auto-?response|out of office|autoreply|otomatik yanıt|abwesenheit|absence)/i;

export function classifyInbound(p: ParsedInbound): InboundKind {
  // RFC 5965 raporu bounce/yanıt kurallarından ÖNCE ele alınır (ARF gövdesindeki özgün ileti başlıkları bounce
  // sanılmasın). Yalnızca `abuse` şikâyettir; yapı ve güven kontrolleri evidence.ts'tedir.
  if (p.arf) return p.arf.feedbackType === "abuse" ? "complaint" : "feedback_other";
  if (
    p.dsn ||
    isSystemSender(p) ||
    /undeliver|delivery status notification|returned mail/i.test(p.subject)
  ) {
    const rcpts = p.dsn?.recipients ?? [];
    if (rcpts.length === 0) return "bounce_other";
    // Birden çok alıcı varsa en ağır sonuç sınıfı değil, EN GÜVENLİSİ seçilir: karışık raporlar otomatik etki üretmez.
    const classes = new Set(rcpts.map((r) => bounceClass(r.action, r.status)));
    if (classes.size === 1) return [...classes][0]!;
    return "bounce_other";
  }
  if (p.autoGenerated || AUTO_SUBJECT.test(p.subject.trim())) return "auto_reply";

  const fresh = freshText(p.text);
  const firstLine = fresh.split("\n").find((l) => l.trim() !== "") ?? "";
  if (
    UNSUB_SINGLE.test(firstLine) ||
    UNSUB_SINGLE.test(p.subject) ||
    UNSUB_PHRASES.test(fresh) ||
    UNSUB_PHRASES.test(p.subject)
  ) {
    return "unsubscribe";
  }
  if (NEGATIVE_PHRASES.test(fresh) || NEGATIVE_PHRASES.test(p.subject)) return "negative";
  if (
    p.inReplyTo.length > 0 ||
    p.references.length > 0 ||
    /^\s*(re|aw|ynt|sv)\s*:/i.test(p.subject)
  ) {
    return "reply";
  }
  return "other";
}

function bounceClass(action: string, status: string | null): InboundKind {
  if (action === "delayed") return "bounce_soft";
  if (!status) return "bounce_other";
  if (status.startsWith("4.")) return "bounce_soft";
  if (status.startsWith("5.7.")) return "bounce_policy";
  if (ADDRESS_GONE_STATUSES.has(status) && action === "failed") return "bounce_hard";
  if (status.startsWith("5.")) return "bounce_other";
  return "bounce_other";
}
