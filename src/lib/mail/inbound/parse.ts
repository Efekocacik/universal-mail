import { parseEmail } from "@/lib/email/address";
import { isValidMessageId } from "../mime/message-id";

/**
 * Gelen ham iletinin (RFC 5322 / MIME) savunmacı ayrıştırıcısı (Aşama 13).
 *
 * Gelen ileti SALDIRGAN GİRDİSİDİR: her başlık ve gövde yalnızca veri olarak okunur. Sınırlar aşılırsa ya da yapı
 * bozuksa `ok:false` döner ve ileti hiçbir otomatik etki üretemez. Gövde saklanmaz; yalnızca sınıflandırma için
 * kısa bir metin parçası çıkarılır.
 */

export const MAX_RAW_BYTES = 256 * 1024;
export const MAX_HEADERS = 100;
export const MAX_HEADER_LINE = 2000;
export const MAX_PART_DEPTH = 4;
export const MAX_PARTS = 20;
/** Sınıflandırma için okunan en çok metin (karakter). */
export const MAX_TEXT_CHARS = 8 * 1024;

export type ParseFailure =
  "too_large" | "malformed" | "too_many_headers" | "too_deep" | "no_headers";

export interface DsnRecipient {
  /** Küçük harfe çevrilmiş adres (`Final-Recipient` / `Original-Recipient`). */
  address: string;
  action: string;
  /** "5.1.1" gibi; geçersizse null. */
  status: string | null;
}

export interface DsnInfo {
  /** `multipart/report; report-type=delivery-status` yapısı mı? */
  structural: boolean;
  recipients: DsnRecipient[];
  /** Raporun içindeki özgün iletinin Message-ID'si (yoksa null). */
  originalMessageId: string | null;
}

export interface ParsedInbound {
  ok: true;
  /** Başlıklar: küçük harf ad → değerler (katlama açılmış). */
  headers: Map<string, string[]>;
  from: { email: string; local: string; domain: string } | null;
  returnPath: string | null;
  messageId: string | null;
  inReplyTo: string[];
  references: string[];
  subject: string;
  /** Üst düzey Content-Type (küçük harf), parametreler hariç. */
  contentType: string;
  /** Otomatik/yanıtsız ileti işaretleri (Auto-Submitted, Precedence, X-Autoreply...). */
  autoGenerated: boolean;
  /** İlk metin parçasının alıntısız, kısaltılmış hâli. */
  text: string;
  dsn: DsnInfo | null;
  /** Ayrıştırmada görülen kuşkulu durumlar; doluysa otomatik etki yapılmaz. */
  suspicious: string[];
}

export type ParseResult = ParsedInbound | { ok: false; reason: ParseFailure };

interface Part {
  headers: Map<string, string[]>;
  body: string;
}

function splitHeadBody(raw: string): { head: string; body: string } | null {
  const m = /\r?\n\r?\n/.exec(raw);
  if (!m) return null;
  return { head: raw.slice(0, m.index), body: raw.slice(m.index + m[0].length) };
}

function parseHeaders(head: string, suspicious: string[]): Map<string, string[]> | "too_many" {
  const map = new Map<string, string[]>();
  const lines = head.split(/\r?\n/);
  const unfolded: string[] = [];
  for (const line of lines) {
    if (/^[ \t]/.test(line) && unfolded.length > 0)
      unfolded[unfolded.length - 1] += ` ${line.trim()}`;
    else unfolded.push(line);
  }
  if (unfolded.length > MAX_HEADERS) return "too_many";
  for (const line of unfolded) {
    if (line === "") continue;
    const idx = line.indexOf(":");
    const name = idx > 0 ? line.slice(0, idx) : "";
    if (!name || !/^[!-9;-~]+$/.test(name) || line.length > MAX_HEADER_LINE) {
      suspicious.push("malformed_header");
      continue;
    }
    const key = name.toLowerCase();
    const arr = map.get(key) ?? [];
    arr.push(line.slice(idx + 1).trim());
    map.set(key, arr);
  }
  return map;
}

const first = (h: Map<string, string[]>, k: string) => h.get(k)?.[0] ?? null;

function paramOf(value: string | null, name: string): string | null {
  if (!value) return null;
  const re = new RegExp(`(?:^|;)\\s*${name}\\s*=\\s*(?:"([^"]*)"|([^;\\s]*))`, "i");
  const m = re.exec(value);
  return m ? (m[1] ?? m[2] ?? null) : null;
}

const typeOf = (ct: string | null) => (ct?.split(";")[0] ?? "text/plain").trim().toLowerCase();

function decodeBody(body: string, encoding: string | null): string {
  const enc = (encoding ?? "7bit").trim().toLowerCase();
  try {
    if (enc === "base64") {
      return Buffer.from(body.replace(/[^A-Za-z0-9+/=]/g, ""), "base64").toString("utf8");
    }
    if (enc === "quoted-printable") {
      const joined = body.replace(/=\r?\n/g, "");
      const bytes: number[] = [];
      for (let i = 0; i < joined.length; i++) {
        const c = joined[i]!;
        if (c === "=" && /^[0-9A-Fa-f]{2}$/.test(joined.slice(i + 1, i + 3))) {
          bytes.push(parseInt(joined.slice(i + 1, i + 3), 16));
          i += 2;
        } else bytes.push(...Buffer.from(c, "utf8"));
      }
      return Buffer.from(bytes).toString("utf8");
    }
  } catch {
    return "";
  }
  return body;
}

/** Çok parçalı gövdeyi parçalara böler (iç içe en çok `MAX_PART_DEPTH`, toplam en çok `MAX_PARTS`). */
function collectParts(
  headers: Map<string, string[]>,
  body: string,
  depth: number,
  budget: { parts: number },
  suspicious: string[],
): Part[] {
  const ct = first(headers, "content-type");
  const type = typeOf(ct);
  if (!type.startsWith("multipart/")) return [{ headers, body }];
  if (depth >= MAX_PART_DEPTH) {
    suspicious.push("too_deep");
    return [];
  }
  const boundary = paramOf(ct, "boundary");
  if (!boundary || boundary.length > 200) {
    suspicious.push("bad_boundary");
    return [];
  }
  const out: Part[] = [];
  const delim = `--${boundary}`;
  const chunks = body.split(delim).slice(1);
  for (const chunk of chunks) {
    if (chunk.startsWith("--")) break; // kapanış sınırı
    if (++budget.parts > MAX_PARTS) {
      suspicious.push("too_many_parts");
      break;
    }
    const piece = chunk.replace(/^\r?\n/, "");
    const hb = splitHeadBody(piece) ?? { head: piece, body: "" };
    const h = parseHeaders(hb.head, suspicious);
    if (h === "too_many") {
      suspicious.push("too_many_headers");
      continue;
    }
    out.push(...collectParts(h, hb.body, depth + 1, budget, suspicious));
  }
  return out;
}

const STATUS_RE = /^([245])\.(\d{1,3})\.(\d{1,3})$/;

function parseDsnBlocks(text: string): DsnRecipient[] {
  const blocks = text.split(/\r?\n\r?\n/).slice(1, 6); // ilk blok iletiye ait, sonrakiler alıcıya ait
  const recipients: DsnRecipient[] = [];
  for (const block of blocks) {
    const fields = new Map<string, string>();
    for (const line of block.replace(/\r?\n[ \t]+/g, " ").split(/\r?\n/)) {
      const i = line.indexOf(":");
      if (i > 0) fields.set(line.slice(0, i).trim().toLowerCase(), line.slice(i + 1).trim());
    }
    const rawRcpt = fields.get("final-recipient") ?? fields.get("original-recipient");
    if (!rawRcpt) continue;
    const addr = rawRcpt
      .replace(/^[a-z0-9-]+\s*;\s*/i, "")
      .replace(/^<|>$/g, "")
      .trim()
      .toLowerCase();
    const parsed = parseEmail(addr);
    if (!parsed) continue;
    const status = fields.get("status")?.trim() ?? "";
    recipients.push({
      address: parsed.email,
      action: (fields.get("action") ?? "").trim().toLowerCase(),
      status: STATUS_RE.test(status) ? status : null,
    });
  }
  return recipients;
}

const MID_RE = /<[^<>\s]{1,240}>/g;

function idsOf(value: string | null | undefined): string[] {
  if (!value) return [];
  return (value.match(MID_RE) ?? []).filter(isValidMessageId).slice(0, 20);
}

/** İletiyi ayrıştırır; sınır aşımı ve bozuk yapıda `ok:false`. */
export function parseInbound(raw: string): ParseResult {
  if (Buffer.byteLength(raw, "utf8") > MAX_RAW_BYTES) return { ok: false, reason: "too_large" };
  // Çıplak CR/NUL: başlık enjeksiyonu ve ayrıştırıcı karışıklığı girişimi.
  if (/\0|\r(?!\n)/.test(raw)) return { ok: false, reason: "malformed" };
  const hb = splitHeadBody(raw);
  if (!hb) return { ok: false, reason: "no_headers" };

  const suspicious: string[] = [];
  const headers = parseHeaders(hb.head, suspicious);
  if (headers === "too_many") return { ok: false, reason: "too_many_headers" };
  if (headers.size === 0) return { ok: false, reason: "no_headers" };
  // Tekil olması gereken başlıkta yinelenme (başlık sahteciliği belirtisi).
  for (const k of ["from", "message-id", "subject", "date", "in-reply-to"]) {
    if ((headers.get(k)?.length ?? 0) > 1) suspicious.push(`duplicate_${k}`);
  }

  const budget = { parts: 0 };
  const parts = collectParts(headers, hb.body, 0, budget, suspicious);
  if (suspicious.includes("too_deep") && parts.length === 0)
    return { ok: false, reason: "too_deep" };

  const fromHeader = first(headers, "from");
  const fromMatch = fromHeader ? (/<([^<>]+)>/.exec(fromHeader)?.[1] ?? fromHeader) : null;
  const fromParsed = fromMatch ? parseEmail(fromMatch.trim().toLowerCase()) : null;
  const rp = first(headers, "return-path");
  const returnPath = rp === null ? null : rp.replace(/^<|>$/g, "").trim();

  const ct = first(headers, "content-type");
  const topType = typeOf(ct);

  let text = "";
  let dsn = null as DsnInfo | null;
  for (const p of parts) {
    const t = typeOf(first(p.headers, "content-type"));
    const decoded = () => decodeBody(p.body, first(p.headers, "content-transfer-encoding"));
    if (t === "text/plain" && !text) {
      text = decoded().slice(0, MAX_TEXT_CHARS);
    } else if (t === "message/delivery-status") {
      const recipients = parseDsnBlocks(decoded());
      dsn = { structural: false, recipients, originalMessageId: dsn?.originalMessageId ?? null };
    } else if (t === "message/rfc822" || t === "text/rfc822-headers") {
      const inner = splitHeadBody(p.body) ?? { head: p.body, body: "" };
      const ih = parseHeaders(inner.head.slice(0, 20_000), []);
      if (ih !== "too_many") {
        const id = idsOf(first(ih, "message-id"))[0] ?? null;
        dsn = dsn
          ? { ...dsn, originalMessageId: dsn.originalMessageId ?? id }
          : { structural: false, recipients: [], originalMessageId: id };
      }
    }
  }
  if (dsn) {
    dsn.structural =
      topType === "multipart/report" &&
      (paramOf(ct, "report-type") ?? "").toLowerCase() === "delivery-status" &&
      dsn.recipients.length > 0;
  }

  const autoSubmitted = (first(headers, "auto-submitted") ?? "no").toLowerCase();
  const precedence = (first(headers, "precedence") ?? "").toLowerCase();
  const autoGenerated =
    autoSubmitted !== "no" ||
    ["bulk", "junk", "auto_reply"].includes(precedence) ||
    headers.has("x-autoreply") ||
    headers.has("x-autorespond") ||
    headers.has("x-auto-response-suppress");

  return {
    ok: true,
    headers,
    from: fromParsed,
    returnPath,
    messageId: idsOf(first(headers, "message-id"))[0] ?? null,
    inReplyTo: idsOf(first(headers, "in-reply-to")),
    references: idsOf((headers.get("references") ?? []).join(" ")),
    subject: (first(headers, "subject") ?? "").slice(0, 300),
    contentType: topType,
    autoGenerated,
    text,
    dsn,
    suspicious,
  };
}
